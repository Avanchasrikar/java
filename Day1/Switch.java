public class Switch {
    public static void main(String[] args) {
        int n=11;

        switch(n){
            case 1:
                System.out.println("hello sir");
                break; // break tells that  come out of the block 
            case 2:
                System.out.println("how are you");
                break;
            case 3:
                System.out.println("ok bye");
            break;
            default:
                System.out.println("ram ram");
        }
    }
}
